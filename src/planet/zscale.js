/* Шкала высот: сырое поле → единицы Azgaar → метры.

   Здесь живёт вся нелинейность рельефа — и прямая (`heightFromRaw`: из суммы
   октав в высоту), и обратная (`heightToZ`: из высоты в сумму октав). Обратная
   нужна не для симметрии: по ней карта планеты принимает географию карты
   Azgaar. Высоты генератора переводятся в z и подкладываются под деталь —
   берег планеты тогда лежит ровно там, где берег на карте, а не «примерно
   похож» (src/planet/source.js).

   Единицы — азгааровские, 0…100 с уровнем моря 20 (docs/planet-map.md, «Что
   взято из Azgaar»): перенесённые из генератора правила — «земля начинается с
   20», матрица биомов, ширина реки из стока — работают без пересчёта. Метры —
   только для показа и для физики (уклоны, перепад высот).

   Сумма октав безразмерна, поэтому у неё есть среднее и разброс (RAW_MEAN,
   RAW_SIGMA), и все пороги заданы в σ: `z = (raw − RAW_MEAN)/RAW_SIGMA`. Держать
   пороги в «единицах шума» нельзя: зерно и амплитуды меняются вместе, а берег
   обязан оставаться на месте при любом seed.

   Океан устроен по-настоящему. Раньше обратная шкала для воды была линейной
   «на глазок» (две σ от берега до дна), и глубина, заданная в метрах, при
   переводе в z и обратно терялась: одиннадцатикилометровый жёлоб рисовался
   пятикилометровым. Теперь обратная функция — **точное обращение** прямой
   кривой, а параметры кривой подобраны под реальную гипсометрию океана:

     • шельф ломается на −200 м (SHELF_DEPTH), как у настоящих материков;
     • ложе выходит на асимптоту около −13,4 км, поэтому жёлоба до −11 км
       помещаются на шкале целиком и рисуются той глубины, какая задана;
     • марокканская кривая (экспонента с коленом) повторяет форму океанского
       ложа: шельф, склон, абиссальная равнина, жёлоб.

   Метр суши отсчитан от уровня моря (h = 20), а не от h = 18, как раньше: при
   переводе высоты в метры нулевая отметка обязана совпадать с берегом, иначе
   «0 м» оказывается на четыре метра выше кромки воды. Якорь Эвереста (8848 м
   на h = 100) сохранён множителем K_LAND. */

import { clamp } from './scale.js';

/** Уровень моря в шкале Azgaar. Ниже — вода, выше — суша. */
export const SEA_LEVEL = 20;
/** Показатель кривой суши: h = 100 даёт 8848 м (K_LAND подобран под это). */
export const HEIGHT_EXPONENT = 2.06;
/** Во сколько раз единиц шкалы больше метров на суше: 80K = 8848^(1/2,06). */
export const K_LAND = 8848 ** (1 / HEIGHT_EXPONENT) / 80;
/** Метров глубины на единицу шкалы: h = 0 даёт 11 000 м. */
export const OCEAN_M_PER_UNIT = 550;

/* ---------- z-шкала: среднее и разброс сырого поля ---------- */

/* Числа измерены на самом поле: сумма октав (elevation.js) имеет среднее 9,0 и
   разброс 8,8 в метрах карты, где мир плоский. Держать их отдельно от генератора
   нельзя: при переходе с цилиндрической выборки шума на плоскую разброс упал с
   10,6 до 8,8, и «берег на 0,52 σ» без правки константы означал бы уже другую
   долю суши (25 % вместо 30). */
export const RAW_MEAN = 9;
export const RAW_SIGMA = 8.8;
/** Граница суши: около 30 % площади процедурного мира остаётся выше неё. */
export const SEA_Z = 0.52;
/** z, дающий Эверест. */
export const LAND_Z = 3;
/** Показатель сушу: равнины широкие, вершины редкие. */
export const LAND_POW = 1.9;

/* ---------- шельф и ложе ---------- */

/** Ширина шельфа в σ: до этих пор глубина растёт по мягкой кривой. */
export const SHELF_Z = 0.18;
/** Единиц шкалы на шельфе: 0,36 × 550 ≈ 200 м — кромка шельфа. */
export const SHELF_DEPTH = 0.36;
/** Асимптота ложа в единицах шкалы: ≈13,4 км — глубже любой настоящей впадины. */
export const ABYSS_DEPTH = 24;
/** Крутизна экспоненты ложа: глубже колена ложе почти плоское. */
export const ABYSS_KNEE = 1.1;

/** Глубина в условных единицах, достигнутая на расстоянии d от берега (в σ). */
const depthUnits = (d) =>
  d <= SHELF_Z
    ? SHELF_DEPTH * (d / SHELF_Z) ** 1.5
    : SHELF_DEPTH + ABYSS_DEPTH * (1 - Math.exp(-(d - SHELF_Z) / ABYSS_KNEE));

/** Расстояние в σ, на котором достигнута такая глубина (точное обращение). */
const depthDistance = (units) => {
  if (units <= SHELF_DEPTH) return SHELF_Z * (clamp(units, 0, SHELF_DEPTH) / SHELF_DEPTH) ** (1 / 1.5);
  const share = clamp((units - SHELF_DEPTH) / ABYSS_DEPTH, 0, 0.999999);
  return SHELF_Z - ABYSS_KNEE * Math.log(1 - share);
};

/** Насколько глубоко в z уходит дно: h = 0 даёт z = SEA_Z − OCEAN_SPAN.
    Величина выведена из кривой ложа, а не назначена: иначе жёлоб не влезает. */
export const OCEAN_SPAN = depthDistance(SEA_LEVEL);

/**
 * Нелинейная шкала: из суммы октав получаем высоту в единицах Azgaar.
 * До уровня моря — океан с шельфом у берега и пологим ложем; выше — равнины,
 * плато и линейный рост выше насыщения.
 */
export const heightFromRaw = (raw) => {
  const z = (raw - RAW_MEAN) / RAW_SIGMA;
  if (z >= SEA_Z) return SEA_LEVEL + 80 * clamp((z - SEA_Z) / (LAND_Z - SEA_Z), 0, 1) ** LAND_POW;
  return SEA_LEVEL - depthUnits(SEA_Z - z);
};

/** Высоты в метрах: плюс — суша, минус — глубина. Ноль — ровно уровень моря. */
export const heightMeters = (h) =>
  h >= SEA_LEVEL ? (K_LAND * (h - SEA_LEVEL)) ** HEIGHT_EXPONENT : -(SEA_LEVEL - h) * OCEAN_M_PER_UNIT;

/** Метры в единицы шкалы — обратная функция, нужна порогам («выше 2000 м»). */
export const heightFromMeters = (m) =>
  m >= 0 ? SEA_LEVEL + Math.abs(m) ** (1 / HEIGHT_EXPONENT) / K_LAND : SEA_LEVEL - Math.abs(m) / OCEAN_M_PER_UNIT;

/**
 * Обратная к `heightFromRaw`: высота Azgaar → z сырого поля.
 *
 * Раньше вода переводилась линейной линейкой в две σ, и круг «метры → z →
 * метры» не сходился: глубину приходилось проверять глазами. Теперь обратная
 * функция — обращение той же кривой, поэтому `heightFromRaw(rawFromHeight(h))`
 * равно `h` для **всей** шкалы, включая воду, и любой рельеф, заданный в метрах
 * (тектоника, эрозия, вулканы), приходит на карту ровно той высоты, какой был
 * задуман.
 */
export const heightToZ = (h) => {
  if (h >= SEA_LEVEL) {
    const t = clamp((h - SEA_LEVEL) / 80, 0, 1) ** (1 / LAND_POW);
    return SEA_Z + t * (LAND_Z - SEA_Z);
  }
  return SEA_Z - depthDistance(SEA_LEVEL - h);
};

/** z самого глубокого дна (h = 0): нижняя граница океанической линейки. */
export const OCEAN_FLOOR_Z = SEA_Z - OCEAN_SPAN;

/** Сырое значение, дающее заданную высоту в единицах шкалы: для порогов. */
export const rawFromHeight = (h) => RAW_MEAN + RAW_SIGMA * heightToZ(h);

/** Сырое значение по высоте в метрах — так физика (тектоника, эрозия) ложится
    на шкалу рельефа: метры остаются метрами на всём диапазоне. */
export const rawFromMeters = (m) => rawFromHeight(heightFromMeters(m));
