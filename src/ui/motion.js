/* Динамика: одно правило на весь интерфейс.

   Движение гасят два независимых решения, и спрашивать надо оба.

   Первое — системное `prefers-reduced-motion`: его ставят в настройках ОС или
   браузера. Второе — тумблер «Анимации» в настройках самой игры: `main.js`
   держит класс `reduce-motion` на `<html>`, а `src/style.css` гасит по нему
   анимации и переходы. Тумблер сильнее: игрок выключает движение в игре и
   ждёт, что оно выключится везде, даже если системная настройка не тронута.

   CSS-правило работает только для того, что двигает сам CSS. Всё, что код
   двигает своим решением — растёт при появлении, играет течением, показывает
   накладку генерации, — обязано спросить `motionOff()`. Ошибка, из-за которой
   это правило появилось: вид карты блоками видел только системную настройку,
   поэтому выключенные анимации не гасили ни появление, ни течение.

   Спрашивать нужно заново перед каждым показом и кадром: настройку можно
   переключить, не закрывая экран. */

/** Системная настройка «меньше движения» — или null там, где её нет. */
export const motionQuery = () =>
  typeof window !== 'undefined' && typeof window.matchMedia === 'function'
    ? window.matchMedia('(prefers-reduced-motion: reduce)')
    : null;

/**
 * Выключено ли движение прямо сейчас. `query` — снимок `motionQuery()`:
 * объект MediaQueryList живой, его `matches` меняется вместе с настройкой
 * системы, поэтому спрашивать можно на каждом кадре, не создавая новый.
 */
export const motionOff = (query = motionQuery()) =>
  (typeof document !== 'undefined' && document.documentElement?.classList?.contains('reduce-motion') === true) ||
  Boolean(query?.matches);
